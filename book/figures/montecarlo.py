import numpy as np, sys
out = sys.argv[1]
rng = np.random.default_rng(1946)
N = 100_000
x, y = rng.random(N), rng.random(N)
inside = x**2 + y**2 <= 1
n_show = 400
pts_in = [(a, b) for a, b, i in zip(x[:n_show], y[:n_show], inside[:n_show]) if i]
pts_out = [(a, b) for a, b, i in zip(x[:n_show], y[:n_show], inside[:n_show]) if not i]
est_show = 4 * inside[:n_show].mean()
cum = np.cumsum(inside)
ns = np.unique(np.round(np.logspace(1, 5, 60)).astype(int))
curve = [(n, 4 * cum[n-1] / n) for n in ns]
fmt = lambda pts: ', '.join(f'{a:.3f}/{b:.3f}' for a, b in pts)
with open(out, 'w', encoding='utf-8') as f:
    f.write('% Generated by a seeded run (numpy default_rng(1946)); do not edit by hand.\n')
    f.write(f'\def\mcInside{{{fmt(pts_in)}}}\n')
    f.write(f'\def\mcOutside{{{fmt(pts_out)}}}\n')
    f.write(f'\def\mcCurve{{{" ".join(f"({n},{e:.4f})" for n, e in curve)}}}\n')
    f.write(f'\def\mcShowN{{{n_show}}}\n\def\mcShowIn{{{len(pts_in)}}}\n\def\mcShowEst{{{est_show:.2f}}}\n')
    f.write(f'\def\mcFinalEst{{{4*cum[-1]/N:.4f}}}\n')
print('shown', n_show, 'inside', len(pts_in), 'est', est_show, 'final', 4*cum[-1]/N)
for n in [10, 100, 1000, 10000, 100000]: print(n, 4*cum[n-1]/n)
